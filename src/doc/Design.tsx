        <Step n="→" title="許容値: σy に低減率を掛ける">
          <Eq n="16" strong tex={String.raw`\sigma_{cl}=\sigma_y\times\left(\dfrac{\sigma_{cl}}{\sigma_y}\right)_{(14)}`} note="局部座屈の許容値。「3つの照査」の ① の答え。" />
        </Step>
