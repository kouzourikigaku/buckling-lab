          <Eq n="13" tex={String.raw`\dfrac{\sigma_u}{\sigma_y}\approx\dfrac{1}{R}\left(1-\dfrac{0.22}{R}\right)=\dfrac{R-0.22}{R^2}\quad(R>0.673)`} note="両縁支持板の式(Eurocode 3 の EN 1993-1-5:2006 と同じ形)。R ≦ 0.673 では 1.0。自由突出板は別の式。理想の線と交わるのは R = 1.22。" />
